-- ------------------------------------------------------------
-- 1a. public.users — Profile extension dari auth.users
--     id = UUID dari auth.users (bukan auto-increment)
--     TIDAK ada kolom password — dikelola Supabase Auth (bcrypt)
-- ------------------------------------------------------------
CREATE TABLE public.users (
  id         UUID        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name       TEXT        NOT NULL DEFAULT '',
  email      TEXT        NOT NULL UNIQUE,
  phone      TEXT        NOT NULL DEFAULT '',
  role       TEXT        NOT NULL DEFAULT 'customer'
               CHECK (role IN ('customer', 'seller', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_email ON public.users (email);
CREATE INDEX idx_users_role  ON public.users (role);
CREATE INDEX idx_users_phone ON public.users (phone);

-- ------------------------------------------------------------
-- 1b. public.stores — Toko Penjual
-- ------------------------------------------------------------
CREATE TABLE public.stores (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID        REFERENCES public.users(id) ON DELETE CASCADE,
  store_name  TEXT        NOT NULL,
  description TEXT,
  address     TEXT,
  phone       TEXT,
  status      TEXT        NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_stores_user_id ON public.stores (user_id);
CREATE INDEX idx_stores_status  ON public.stores (status);

-- ------------------------------------------------------------
-- 1c. public.products — Katalog Produk
-- ------------------------------------------------------------
CREATE TABLE public.products (
  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id   BIGINT      REFERENCES public.stores(id) ON DELETE SET NULL,
  store_name TEXT        NOT NULL DEFAULT 'Toko Nelayan',
  name       TEXT        NOT NULL,
  price      NUMERIC     NOT NULL CHECK (price >= 0),
  category   TEXT        NOT NULL,
  stock      INT         NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image      TEXT,
  unit       TEXT        NOT NULL DEFAULT 'kg',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_products_store_id ON public.products (store_id);
CREATE INDEX idx_products_category ON public.products (category);

-- ------------------------------------------------------------
-- 1d. public.orders — Pesanan Pelanggan
-- ------------------------------------------------------------
CREATE TABLE public.orders (
  id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        UUID        REFERENCES public.users(id) ON DELETE SET NULL,
  user_name      TEXT        NOT NULL DEFAULT 'Pelanggan',
  seller_id      UUID        REFERENCES public.users(id) ON DELETE SET NULL,
  store_id       BIGINT      REFERENCES public.stores(id) ON DELETE SET NULL,
  store_name     TEXT,
  total_amount   NUMERIC     NOT NULL CHECK (total_amount >= 0),
  shipping_fee   NUMERIC     NOT NULL DEFAULT 0,
  status         TEXT        NOT NULL DEFAULT 'Menunggu Konfirmasi',
  escrow_status  TEXT        NOT NULL DEFAULT 'pending_payment',
  items          JSONB       NOT NULL DEFAULT '[]',
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_orders_user_id   ON public.orders (user_id);
CREATE INDEX idx_orders_seller_id ON public.orders (seller_id);
CREATE INDEX idx_orders_store_id  ON public.orders (store_id);
CREATE INDEX idx_orders_status    ON public.orders (status);
CREATE INDEX idx_orders_created   ON public.orders (created_at DESC);

-- ------------------------------------------------------------
-- 1e. public.user_logs — Log Aktivitas & Demografi Pengunjung
-- ------------------------------------------------------------
CREATE TABLE public.user_logs (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID        REFERENCES public.users(id) ON DELETE SET NULL,
  user_name   TEXT        NOT NULL DEFAULT 'Pengunjung',
  action      TEXT        NOT NULL, -- 'login' | 'register' | 'purchase' | 'page_view'
  ip_address  TEXT,
  city        TEXT,
  region      TEXT,
  country     TEXT,
  device_type TEXT,                 -- 'Mobile' | 'Desktop' | 'Tablet'
  metadata    JSONB       NOT NULL DEFAULT '{}',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
