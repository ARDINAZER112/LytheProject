CREATE INDEX idx_user_logs_user_id    ON public.user_logs (user_id);
CREATE INDEX idx_user_logs_action     ON public.user_logs (action);
CREATE INDEX idx_user_logs_created_at ON public.user_logs (created_at DESC);

-- ------------------------------------------------------------
-- 1f. public.order_chats — Ruang Chat 3 Pihak per Pesanan
--     (buyer, seller, admin berkomunikasi dalam 1 pesanan)
-- ------------------------------------------------------------
CREATE TABLE public.order_chats (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT      NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  sender_id   UUID        REFERENCES public.users(id) ON DELETE SET NULL,
  sender_name TEXT        NOT NULL DEFAULT 'Pengguna',
  sender_role TEXT        NOT NULL DEFAULT 'buyer', -- 'buyer' | 'seller' | 'admin' | 'system'
  text        TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
