-- ── 6.1 Kolom baru di tabel orders (escrow, seller, toko) ────
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS seller_id     UUID REFERENCES public.users(id) ON DELETE SET NULL;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS store_id      BIGINT REFERENCES public.stores(id) ON DELETE SET NULL;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS store_name    TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS shipping_fee  NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS escrow_status TEXT NOT NULL DEFAULT 'pending_payment';
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_orders_seller_id ON public.orders (seller_id);
CREATE INDEX IF NOT EXISTS idx_orders_store_id  ON public.orders (store_id);

-- Isi seller_id/store_name pada pesanan lama yang mungkin sudah ada,
-- dicocokkan lewat nama toko yang tersimpan di kolom items (JSONB)
UPDATE public.orders o
SET seller_id  = COALESCE(o.seller_id, s.user_id),
    store_id   = COALESCE(o.store_id, s.id),
    store_name = COALESCE(o.store_name, s.store_name)
FROM public.stores s
WHERE o.store_name IS NULL
  AND o.items IS NOT NULL
  AND jsonb_array_length(o.items) > 0
  AND s.store_name = (o.items->0->>'store_name');

-- ── 6.2 Tabel order_chats (ruang chat 3 pihak per pesanan) ───
CREATE TABLE IF NOT EXISTS public.order_chats (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT      NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  sender_id   UUID        REFERENCES public.users(id) ON DELETE SET NULL,
  sender_name TEXT        NOT NULL DEFAULT 'Pengguna',
  sender_role TEXT        NOT NULL DEFAULT 'buyer',
  text        TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_order_chats_order_id ON public.order_chats (order_id);
ALTER TABLE public.order_chats ENABLE ROW LEVEL SECURITY;

