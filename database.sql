ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;

-- ── 6.4 RLS helper functions (kalau belum ada) ───────────────
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN LANGUAGE sql SECURITY DEFINER AS $$
  SELECT EXISTS (SELECT 1 FROM public.users WHERE id = auth.uid() AND role = 'admin');
$$;

-- ── 6.5 Perbaikan & tambahan RLS policy untuk orders ─────────
-- Hapus dulu kalau sudah ada (supaya aman diulang), lalu buat ulang
DROP POLICY IF EXISTS "orders: lihat pesanan sendiri"       ON public.orders;
DROP POLICY IF EXISTS "orders: seller lihat pesanan masuk"  ON public.orders;
DROP POLICY IF EXISTS "orders: seller update pesanan masuk" ON public.orders;
DROP POLICY IF EXISTS "orders: buat pesanan"                ON public.orders;
DROP POLICY IF EXISTS "orders: buyer update pesanan sendiri" ON public.orders;
DROP POLICY IF EXISTS "orders: admin full access"           ON public.orders;

CREATE POLICY "orders: lihat pesanan sendiri"
  ON public.orders FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "orders: seller lihat pesanan masuk"
  ON public.orders FOR SELECT USING (auth.uid() = seller_id);

CREATE POLICY "orders: seller update pesanan masuk"
  ON public.orders FOR UPDATE USING (auth.uid() = seller_id);

CREATE POLICY "orders: buat pesanan"
  ON public.orders FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "orders: buyer update pesanan sendiri"
  ON public.orders FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "orders: admin full access"
  ON public.orders FOR ALL USING (public.is_admin());

-- ── 6.6 RLS policy untuk order_chats ──────────────────────────
DROP POLICY IF EXISTS "order_chats: akses pihak terkait pesanan" ON public.order_chats;

CREATE POLICY "order_chats: akses pihak terkait pesanan"
  ON public.order_chats FOR ALL
  USING (
    EXISTS (SELECT 1 FROM public.orders o WHERE o.id = order_id AND (o.user_id = auth.uid() OR o.seller_id = auth.uid()))
    OR public.is_admin()
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM public.orders o WHERE o.id = order_id AND (o.user_id = auth.uid() OR o.seller_id = auth.uid()))
    OR public.is_admin()
  );

-- ── 6.7 RLS policy untuk support_tickets ──────────────────────
DROP POLICY IF EXISTS "support_tickets: buat tiket"  ON public.support_tickets;
DROP POLICY IF EXISTS "support_tickets: baca tiket"  ON public.support_tickets;
DROP POLICY IF EXISTS "support_tickets: admin update" ON public.support_tickets;

CREATE POLICY "support_tickets: buat tiket"
  ON public.support_tickets FOR INSERT WITH CHECK (true);

CREATE POLICY "support_tickets: baca tiket"
  ON public.support_tickets FOR SELECT
  USING (user_id IS NULL OR auth.uid() = user_id OR public.is_admin());

CREATE POLICY "support_tickets: admin update"
  ON public.support_tickets FOR UPDATE USING (public.is_admin());

