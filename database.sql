  status             TEXT        NOT NULL DEFAULT 'Terbuka',
  admin_reply        TEXT,
  ip_address         TEXT,
  user_agent         TEXT,
  visitor_device_id  TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
